"""Figures for Chapter 11 (conditioning and conditional expectation)."""
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy import stats

from probnotes.conditional import (binned_conditional_mean, midpoints, partition_expectation,
                                   poisson_sum_conditional, sample_exponential_sum,
                                   sample_poisson_sum)
from probnotes.style import COBALT, GOLD, GREY, INK, use_style

GREEN = "#1BAF7A"


def omega_variable(w):
    """The random variable X(omega) on Omega = (0, 1) drawn in the partition figure."""
    return 1.0 + np.sin(3 * np.pi * w) + w


def partition(out):
    """E[X | G] as cell averages, for G generated by 4 and by 16 intervals of (0, 1)."""
    w = midpoints(0.0, 1.0, 4000)
    p = np.full(w.size, 1.0 / w.size)
    x = omega_variable(w)
    fig, axes = plt.subplots(1, 2, figsize=(6.8, 2.35), sharey=True)
    for ax, k in zip(axes, (4, 16)):
        xhat = partition_expectation(x, p, np.floor(w * k))
        ax.fill_between(w, x, xhat, where=x >= xhat, color=COBALT, alpha=0.15, lw=0)
        ax.fill_between(w, x, xhat, where=x < xhat, color=GOLD, alpha=0.2, lw=0)
        ax.plot(w, x, color=GREY, lw=1.2, label=r"$X(\omega)$")
        for j in range(k):                                   # one flat piece per cell
            cell = (w >= j / k) & (w < (j + 1) / k)
            ax.plot(w[cell], xhat[cell], color=COBALT, lw=2.0,
                    label=r"$\mathbb{E}[X\mid\mathcal{G}]$" if j == 0 else None)
        ax.set_xticks(np.arange(0, k + 1) / k, minor=True)
        ax.grid(False, axis="x")
        ax.grid(True, axis="x", which="minor", color="#E6E8EE")
        ax.set(xlim=(0, 1), xlabel=r"$\omega$", title=f"$\\mathcal{{G}}$ generated by {k} intervals")
        ax.legend(loc="upper left", fontsize=7.5)
    fig.tight_layout()
    fig.savefig(out / "ch11-partition.pdf")
    plt.close(fig)


def poisson(out, lam=2.0, mu=3.0, m0=6, n=200_000, seed=2026):
    """The law of X given Z = m (Poisson pair) and h(m) = E[X | Z = m] against simulation."""
    p = lam / (lam + mu)
    x, z = sample_poisson_sum(n, lam, mu, seed=seed)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.8, 2.45))
    k = np.arange(m0 + 1)
    sel = x[z == m0]
    freq = np.bincount(sel, minlength=m0 + 1)[: m0 + 1] / sel.size
    a1.bar(k, poisson_sum_conditional(lam, mu, m0), color=COBALT, alpha=0.35, width=0.7,
           label="from the joint density")
    a1.plot(k, stats.binom.pmf(k, m0, p), "o", color=GOLD, ms=5, label=f"$B({m0},{p:g})$")
    a1.plot(k, freq, "D", color=GREEN, ms=3.2, label=f"simulation ({sel.size} pairs)")
    a1.set(xlabel="$k$", title=f"$\\mathbb{{P}}(X=k\\mid Z={m0})$", xticks=k)
    a1.legend(fontsize=7, loc="upper right")
    ms = np.arange(0, 13)
    means = np.array([x[z == m].mean() for m in ms])
    ses = np.array([x[z == m].std(ddof=1) / np.sqrt((z == m).sum()) for m in ms])
    a2.plot(ms, p * ms, color=COBALT, lw=1.4, label=f"$h(m)={p:g}\\,m$")
    a2.errorbar(ms, means, yerr=2 * ses, fmt="s", color=GOLD, ms=3.5, capsize=2, lw=1,
                label="averages of $X$ given $Z=m$")
    a2.set(xlabel="$m$", title=r"$\mathbb{E}[X\mid Z=m]$")
    a2.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out / "ch11-poisson.pdf")
    plt.close(fig)


def exponential(out, n=200_000, seed=2026):
    """E[X | X + Y] = Z / 2 for i.i.d. exponentials, by binning; conditional histograms."""
    x, z = sample_exponential_sum(n, 1.0, seed=seed)
    edges = np.arange(0.0, 6.0001, 0.25)
    b = binned_conditional_mean(z, x, edges)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.8, 2.5))
    a1.scatter(z[:2000], x[:2000], s=1.5, color=GREY, alpha=0.45, lw=0, rasterized=True)
    t = np.linspace(0, 6, 50)
    a1.plot(t, t / 2, color=COBALT, lw=1.4, label=r"$h(z)=z/2$")
    a1.errorbar(b.mean_z, b.mean_x, yerr=2 * b.se_x, fmt="o", color=GOLD, ms=2.8, capsize=1.5,
                lw=0.9, label="bin averages of $X$")
    a1.set(xlim=(0, 6), ylim=(0, 5), xlabel="$z$", ylabel="$x$", title=r"$(Z, X)$ and $\mathbb{E}[X\mid Z]$")
    a1.legend(fontsize=7, loc="upper left")
    for z0, col in ((1.0, COBALT), (3.0, GOLD)):
        sel = x[np.abs(z - z0) < 0.05]
        a2.hist(sel, bins=np.linspace(0, z0, 16), density=True, color=col, alpha=0.35,
                label=f"$X$ given $|Z-{z0:g}|<0.05$ ({sel.size})")
        a2.hlines(1 / z0, 0, z0, color=col, lw=1.6)
    a2.set(xlim=(0, 3.2), ylim=(0, 1.5), xlabel="$x$", title="conditional histograms and $U(0,z)$")
    a2.legend(fontsize=7, loc="upper right")
    fig.tight_layout()
    fig.savefig(out / "ch11-exponential.pdf")
    plt.close(fig)


def main(out):
    use_style()
    partition(out)
    poisson(out)
    exponential(out)


if __name__ == "__main__":
    import pathlib
    main(pathlib.Path(__file__).resolve().parents[2] / "latex" / "figures")
