def sample_die_coins(n: int, p: float = 0.5, faces: int = 6, seed=None):
    """``n`` draws of ``(N, X)``: ``N`` is a fair die with ``faces`` faces, and given ``N``,
    ``X`` is the number of heads in ``N`` tosses of a coin with ``P(heads) = p``."""
    rng = np.random.default_rng(seed)
    N = rng.integers(1, faces + 1, size=n)
    X = rng.binomial(N, p)
    return N, X


def die_coins_moments(p: float = 0.5, faces: int = 6) -> TotalVariance:
    """Exact ``E[X]``, ``var(X)``, ``var(E[X|N]) = p^2 var(N)`` and ``E[var(X|N)] = p(1-p) E[N]``
    for the die-and-coins experiment."""
    EN = (faces + 1) / 2
    VN = (faces ** 2 - 1) / 12
    vm, mv = p * p * VN, p * (1 - p) * EN
    return TotalVariance(p * EN, vm + mv, vm, mv)


@dataclass
class NestedVariance:
    """Estimates of the two terms of the law of total variance from a nested simulation."""
    within: float          # average of the within-group sample variances: estimates E[var(X|N)]
    between_raw: float     # sample variance of the group means: estimates var(E[X|N]) + E[var(X|N)]/k
    between: float         # between_raw - within / k: unbiased for var(E[X|N])
    total: float           # between + within: estimates var(X)
    within_se: float       # standard error of ``within``
    between_raw_se: float  # standard error of ``between_raw`` (from the fourth moment of the group means)


def nested_variance(groups) -> NestedVariance:
    """Analyse a nested simulation ``groups[r, s]``: row ``r`` shares one first-stage draw and holds
    ``k`` independent second-stage draws given it.

    Given the first stage, the row mean has variance ``var(X | N) / k``, so the variance of the row
    means overestimates ``var(E[X | N])`` by ``E[var(X | N)] / k``; ``between`` removes this bias.
    """
    g = np.asarray(groups, dtype=float)
    if g.ndim != 2 or g.shape[1] < 2:
        raise ValueError("groups must be a table with at least two draws per row")
    R, k = g.shape
    s2 = g.var(axis=1, ddof=1)
    within = float(s2.mean())
    means = g.mean(axis=1)
    between_raw = float(means.var(ddof=1))
    between = between_raw - within / k
    m4 = float(np.mean((means - means.mean()) ** 4))
    return NestedVariance(within, between_raw, between, between + within,
                          float(s2.std(ddof=1) / np.sqrt(R)),
                          float(np.sqrt(max(m4 - between_raw ** 2, 0.0) / R)))


def sample_die_coins_nested(R: int, k: int, p: float = 0.5, faces: int = 6, seed=None) -> np.ndarray:
    """A nested simulation of the die-and-coins experiment: ``R`` rolls of the die and, for each
    roll ``N_r``, ``k`` independent numbers of heads in ``N_r`` tosses. Returns ``groups[r, s]``."""
    rng = np.random.default_rng(seed)
    N = rng.integers(1, faces + 1, size=R)
    return rng.binomial(np.repeat(N[:, None], k, axis=1), p)


def sample_random_sum(counts, sampler: Callable, seed=None) -> np.ndarray:
    """Random sums ``S = X_1 + ... + X_N``, one for each entry of ``counts``.

    ``sampler(rng, m)`` returns ``m`` i.i.d. summands; they are drawn all at once and split by
    ``counts`` (an empty sum is ``0``)."""
    rng = np.random.default_rng(seed)
    counts = np.asarray(counts, dtype=int)
    if (counts < 0).any():
        raise ValueError("the number of terms is non-negative")
    x = np.asarray(sampler(rng, int(counts.sum())), dtype=float)
    ends = np.cumsum(counts)
    c = np.concatenate([[0.0], np.cumsum(x)])
    return c[ends] - c[ends - counts]


def random_sum_moments(EN: float, VN: float, mu: float, s2: float):
    """``(E[S], var(S))`` for ``S = X_1 + ... + X_N``, ``N`` independent of the i.i.d. ``X_i``:
    ``E[S] = E[N] mu`` and ``var(S) = E[N] s2 + var(N) mu^2``."""
    return EN * mu, EN * s2 + VN * mu * mu


