def thinning_table(lam: float, p: float, n_max: int) -> np.ndarray:
    """``f[n, k] = P(X = n, Y = k)`` for ``X ~ P(lam)`` and ``Y | X = n ~ B(n, p)``,
    ``0 <= n, k <= n_max`` (the mass with ``X > n_max`` is left out)."""
    n = np.arange(n_max + 1)
    return stats.poisson.pmf(n, lam)[:, None] * stats.binom.pmf(n[None, :], n[:, None], p)


def sample_thinning(n: int, lam: float, p: float, seed=None):
    """``n`` draws of ``(X, Y)``: ``X ~ P(lam)`` and, given ``X``, ``Y ~ B(X, p)`` (each of the
    ``X`` points is kept with probability ``p``)."""
    rng = np.random.default_rng(seed)
    X = rng.poisson(lam, size=n)
    return X, rng.binomial(X, p)


def negbin_pmf(k, alpha: float, lam: float) -> np.ndarray:
    """Law ``BN(alpha, lam/(lam+1))`` of ``Y`` when ``Y | X = x ~ P(x)`` and ``X ~ Gamma(alpha, lam)``:
    ``Gamma(alpha+k) / (Gamma(alpha) k!) (lam/(lam+1))^alpha (1/(lam+1))^k``, ``k = 0, 1, ...``."""
    k = np.asarray(k, dtype=float)
    logp = (special.gammaln(alpha + k) - special.gammaln(alpha) - special.gammaln(k + 1)
            + alpha * np.log(lam / (lam + 1)) - k * np.log(lam + 1))
    return np.where(k >= 0, np.exp(logp), 0.0)


def poisson_gamma_pmf_quad(k: int, alpha: float, lam: float) -> float:
    """``P(Y = k) = int_0^inf e^{-x} x^k / k! f_X(x) dx`` by numerical quadrature (a check of
    :func:`negbin_pmf` that does not use the Gamma integral)."""
    def integrand(x):
        return stats.poisson.pmf(k, x) * stats.gamma.pdf(x, alpha, scale=1 / lam)
    val, _ = integrate.quad(integrand, 0, np.inf, limit=200)
    return float(val)


def gamma_posterior(k, alpha: float, lam: float):
    """Shape and rate of the law ``Gamma(alpha + k, lam + 1)`` of ``X`` given ``Y = k``; its mean is
    ``E[X | Y = k] = (alpha + k) / (lam + 1)``."""
    k = np.asarray(k, dtype=float)
    return alpha + k, lam + 1.0 + 0 * k


def sample_poisson_gamma(n: int, alpha: float, lam: float, seed=None):
    """``n`` draws of ``(X, Y)``: ``X ~ Gamma(alpha, lam)`` (``lam`` a rate) and ``Y | X ~ P(X)``."""
    rng = np.random.default_rng(seed)
    X = rng.gamma(alpha, 1 / lam, size=n)
    return X, rng.poisson(X)


def sample_gamma_conditional(n: int, seed=None):
    """``n`` draws of the pair ``(X, Y)`` of the worked exercise with ``f_Y(y) = y^{-2} 1{y >= 1}`` and
    ``X | Y = y ~ Gamma(2, y)``: ``X ~ Exp(1)``, ``W ~ Exp(1)`` independent, and ``Y = 1 + W / X``
    (given ``X = x``, ``Y - 1 ~ Exp(x)``)."""
    rng = np.random.default_rng(seed)
    X = rng.exponential(1.0, size=n)
    return X, 1.0 + rng.exponential(1.0, size=n) / X


def beta_binomial_pmf(k, n: int, a: float, b: float) -> np.ndarray:
    """``P(X = k)`` for ``X | P = x ~ B(n, x)`` and ``P ~ Beta(a, b)``:
    ``C(n, k) B(a + k, b + n - k) / B(a, b)``."""
    k = np.asarray(k, dtype=float)
    ok = (k >= 0) & (k <= n)
    kk = np.where(ok, k, 0)
    logp = (special.gammaln(n + 1) - special.gammaln(kk + 1) - special.gammaln(n - kk + 1)
            + special.betaln(a + kk, b + n - kk) - special.betaln(a, b))
    return np.where(ok, np.exp(logp), 0.0)


def beta_posterior(k, n: int, a: float, b: float):
    """Parameters ``(a + k, b + n - k)`` of the Beta law of ``P`` given ``X = k``; its mean is
    ``(a + k) / (a + b + n)``."""
    k = np.asarray(k, dtype=float)
    return a + k, b + n - k


