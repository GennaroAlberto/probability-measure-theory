# ---------------------------------------------------------------------------
# Discrete tables
# ---------------------------------------------------------------------------


def _table(f, ndim: int = 2) -> np.ndarray:
    f = np.asarray(f, dtype=float)
    if f.ndim != ndim:
        raise ValueError(f"a joint discrete density here is a {ndim}-dimensional table")
    if np.isnan(f).any() or (f < 0).any():
        raise ValueError("a joint discrete density has non-negative entries")
    if not np.isclose(f.sum(), 1.0, atol=1e-9):
        raise ValueError("a joint discrete density sums to 1")
    return f


def conditional_moments(f, xvals):
    """Column-wise conditional moments of ``X`` given ``Y`` from ``f[i, j] = P(X=x_i, Y=y_j)``.

    Returns ``(fY, h, v)``: the marginal density of ``Y``, ``h[j] = E[X | Y = y_j]`` and
    ``v[j] = var(X | Y = y_j)``, the mean and the variance of the conditional density
    ``f_{X|Y=y_j}``. Columns with ``f_Y(y_j) = 0`` give ``nan`` (the notes leave them arbitrary).
    """
    f = _table(f)
    x = np.asarray(xvals, dtype=float)
    if x.shape != (f.shape[0],):
        raise ValueError("one value of X per row of the table")
    fY = f.sum(axis=0)
    with np.errstate(invalid="ignore", divide="ignore"):
        h = np.where(fY > 0, (x[:, None] * f).sum(axis=0) / np.where(fY > 0, fY, 1.0), np.nan)
        m2 = np.where(fY > 0, (x[:, None] ** 2 * f).sum(axis=0) / np.where(fY > 0, fY, 1.0), np.nan)
    v = np.maximum(m2 - h ** 2, 0.0, where=~np.isnan(h), out=np.full_like(h, np.nan))
    return fY, h, v


@dataclass
class TotalVariance:
    """The two sides of ``var(X) = var(E[X | Y]) + E[var(X | Y)]``."""
    mean: float           # E[X] = E[E[X | Y]]
    var: float            # var(X), computed directly
    var_of_mean: float    # var(E[X | Y]): the part of var(X) explained by Y
    mean_of_var: float    # E[var(X | Y)]: the part left once Y is known

    @property
    def gap(self) -> float:
        """``var(X) - var(E[X|Y]) - E[var(X|Y)]``: zero by the law of total variance."""
        return self.var - self.var_of_mean - self.mean_of_var


def total_variance(f, xvals) -> TotalVariance:
    """Both sides of the law of total variance for a finite joint table ``f[i, j]``."""
    f = _table(f)
    x = np.asarray(xvals, dtype=float)
    fY, h, v = conditional_moments(f, x)
    fX = f.sum(axis=1)
    mean = float(x @ fX)
    var = float(((x - mean) ** 2) @ fX)
    ok = fY > 0
    vm = float(((h[ok] - mean) ** 2) @ fY[ok])
    mv = float(v[ok] @ fY[ok])
    return TotalVariance(mean, var, vm, mv)


def is_mean_independent(f, xvals, tol: float = 1e-12) -> bool:
    """``True`` if ``E[X | Y = y_j] = E[X]`` for every ``y_j`` with ``f_Y(y_j) > 0``."""
    f = _table(f)
    fY, h, _ = conditional_moments(f, xvals)
    mean = float(np.asarray(xvals, dtype=float) @ f.sum(axis=1))
    return bool(np.all(np.abs(h[fY > 0] - mean) <= tol))


def is_independent(f, tol: float = 1e-12) -> bool:
    """``True`` if ``f[i, j] = f_X(x_i) f_Y(y_j)`` for every ``i, j``."""
    f = _table(f)
    return bool(np.all(np.abs(f - np.outer(f.sum(axis=1), f.sum(axis=0))) <= tol))


def square_example():
    """The counterexample of the notes: ``X`` uniform on ``{-2, -1, 1, 2}`` and ``Y = X^2``.

    Returns ``(f, xvals, yvals)`` with ``f[i, j] = P(X = xvals[i], Y = yvals[j])``.
    """
    xvals = np.array([-2.0, -1.0, 1.0, 2.0])
    yvals = np.array([1.0, 4.0])
    f = np.array([[float(x * x == y) / 4 for y in yvals] for x in xvals])
    return f, xvals, yvals


def conditional_independence_gap(f) -> float:
    """Largest ``|f(i, j | k) - f(i | k) f(j | k)|`` over ``i, j`` and the ``k`` with ``f_3(k) > 0``.

    ``f[i, j, k] = P(Y_1 = a_i, Y_2 = b_j, Y_3 = c_k)``. The gap is ``0`` exactly when ``Y_1`` and
    ``Y_2`` are conditionally independent given ``Y_3`` (the discrete form of the definition).
    """
    f = _table(f, ndim=3)
    f3 = f.sum(axis=(0, 1))
    gap = 0.0
    for k in np.flatnonzero(f3 > 0):
        c = f[:, :, k] / f3[k]
        gap = max(gap, float(np.abs(c - np.outer(c.sum(axis=1), c.sum(axis=0))).max()))
    return gap


