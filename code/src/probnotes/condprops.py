@dataclass
class BinnedMeans:
    """Averages of ``x`` over the bins ``[edges[j], edges[j+1])`` of ``y``."""
    edges: np.ndarray
    count: np.ndarray
    mean: np.ndarray
    se: np.ndarray

    @property
    def centres(self) -> np.ndarray:
        return (self.edges[:-1] + self.edges[1:]) / 2


def binned_means(y, x, edges) -> BinnedMeans:
    """Averages of ``x`` over bins of ``y``, with standard errors (``nan`` for bins with fewer than
    two samples); samples outside ``[edges[0], edges[-1])`` are ignored."""
    y, x = np.asarray(y, dtype=float), np.asarray(x, dtype=float)
    edges = np.asarray(edges, dtype=float)
    j = np.searchsorted(edges, y, side="right") - 1
    ok = (j >= 0) & (j < len(edges) - 1)
    j, xx = j[ok], x[ok]
    nb = len(edges) - 1
    cnt = np.bincount(j, minlength=nb).astype(float)
    with np.errstate(invalid="ignore", divide="ignore"):
        m = np.bincount(j, weights=xx, minlength=nb) / cnt
        ss = np.bincount(j, weights=(xx - m[j]) ** 2, minlength=nb)
        se = np.where(cnt > 1, np.sqrt(ss / (cnt - 1) / cnt), np.nan)
    return BinnedMeans(edges, cnt.astype(int), m, se)
