def bin_index(y, edges) -> np.ndarray:
    """Index ``j`` of the bin ``[edges[j], edges[j+1])`` containing each ``y``; the first and last bins
    are extended to ``-inf`` and ``+inf``, so that the bins partition the real line."""
    y = np.asarray(y, dtype=float)
    edges = np.asarray(edges, dtype=float)
    return np.clip(np.searchsorted(edges, y, side="right") - 1, 0, len(edges) - 2)


def indicator_features(y, edges) -> np.ndarray:
    """Design matrix ``D[s, j] = 1{y_s in bin j}`` of the bins of :func:`bin_index`.

    The matrix is dense, with ``len(y) * (len(edges) - 1)`` entries: use it on small samples, and
    :func:`bin_regression` for large ones.
    """
    y = np.asarray(y, dtype=float)
    j = bin_index(y, edges)
    D = np.zeros((y.size, len(edges) - 1))
    D[np.arange(y.size), j] = 1.0
    return D


def bin_regression(x, y, edges) -> np.ndarray:
    """Coefficients of the least-squares regression of ``x`` on the indicators of the bins of ``y``,
    computed without the design matrix: the averages of ``x`` over the bins (``0`` for empty bins).

    This is ``l2_projection(x, indicator_features(y, edges))[0]``, the conditional expectation of
    ``x`` given the sigma-algebra generated by the bins, under the empirical measure of the sample.
    Predict with ``coef[bin_index(y_new, edges)]``.
    """
    x = np.asarray(x, dtype=float)
    j = bin_index(y, edges)
    K = len(edges) - 1
    cnt = np.bincount(j, minlength=K)
    tot = np.bincount(j, weights=x, minlength=K)
    return np.divide(tot, cnt, out=np.zeros(K), where=cnt > 0)


def l2_projection(x, features):
    """Least-squares projection of the sample ``x`` on the span of the columns of ``features``.

    Returns ``(coef, fitted)``. Under the empirical measure of the sample this is the orthogonal
    projection in ``L^2``; for indicator features of a partition, ``coef`` are the averages of
    ``x`` over the cells, that is, the conditional expectation given the sigma-algebra generated
    by the cells (empty cells get coefficient ``0``).
    """
    x = np.asarray(x, dtype=float)
    F = np.asarray(features, dtype=float)
    coef, *_ = np.linalg.lstsq(F, x, rcond=None)
    return coef, F @ coef


def affine_predictor(x, y):
    """``(a, b)`` minimising the sample mean of ``(x - a - b y)^2``:
    ``b = cov(x, y) / var(y)`` and ``a = mean(x) - b mean(y)``."""
    x, y = np.asarray(x, dtype=float), np.asarray(y, dtype=float)
    b = np.cov(x, y, ddof=0)[0, 1] / y.var()
    return float(x.mean() - b * y.mean()), float(b)


def mse(x, pred) -> float:
    """Mean squared error ``mean((x - pred)^2)``."""
    return float(np.mean((np.asarray(x, dtype=float) - np.asarray(pred, dtype=float)) ** 2))


def sample_signal(n: int, sigma: float, seed=None):
    """``n`` draws of ``(X, Y)``: the signal ``X ~ Exp(1)`` and the received ``Y = X + W`` with
    noise ``W ~ N(0, sigma^2)`` independent of ``X``."""
    rng = np.random.default_rng(seed)
    X = rng.exponential(1.0, size=n)
    return X, X + sigma * rng.standard_normal(n)


def signal_posterior_mean(y, sigma: float) -> np.ndarray:
    """``E[X | Y = y]`` for ``X ~ Exp(1)``, ``Y = X + W``, ``W ~ N(0, sigma^2)``.

    Given ``Y = y``, ``X`` is ``N(y - sigma^2, sigma^2)`` conditioned on ``(0, inf)``, so
    ``E[X | Y = y] = m + sigma phi(m/sigma) / Phi(m/sigma)`` with ``m = y - sigma^2``. The ratio
    ``phi/Phi`` is computed on the log scale, which keeps it accurate for very negative ``y``.
    """
    y = np.asarray(y, dtype=float)
    m = y - sigma ** 2
    a = m / sigma
    ratio = np.exp(stats.norm.logpdf(a) - special.log_ndtr(a))
    return m + sigma * ratio


def signal_density(y, sigma: float) -> np.ndarray:
    """Density of ``Y = X + W``: ``f_Y(y) = exp(sigma^2/2 - y) Phi((y - sigma^2)/sigma)``."""
    y = np.asarray(y, dtype=float)
    return np.exp(sigma ** 2 / 2 - y + special.log_ndtr((y - sigma ** 2) / sigma))


def signal_mse(sigma: float) -> float:
    """``E[(X - E[X|Y])^2] = E[X^2] - E[h(Y)^2] = 2 - int h(y)^2 f_Y(y) dy`` (Pythagoras), by
    quadrature."""
    def integrand(y):
        return signal_posterior_mean(y, sigma) ** 2 * signal_density(y, sigma)
    lo = -12 * sigma
    val = sum(integrate.quad(integrand, a, b, limit=200)[0]
              for a, b in [(lo, 0.0), (0.0, 10.0), (10.0, np.inf)])
    return float(2.0 - val)


