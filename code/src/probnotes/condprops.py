"""Properties of conditional expectation (Chapter 12).

Five groups of tools, in the order of the chapter:

* **Discrete tables.** A joint discrete density with finitely many values is a table
  ``f[i, j] = P(X = x_i, Y = y_j)``. :func:`conditional_moments` returns, column by column, the
  conditional mean ``h(y_j) = E[X | Y = y_j]`` and the conditional variance
  ``var(X | Y = y_j)``; :func:`total_variance` splits ``var(X)`` into ``var(E[X | Y])`` and
  ``E[var(X | Y)]`` (the law of total variance). :func:`is_mean_independent` and
  :func:`is_independent` separate the two notions, and :func:`square_example` is the table of the
  notes' counterexample (``X`` uniform on ``{-2, -1, 1, 2}``, ``Y = X^2``).
  :func:`conditional_independence_gap` measures how far a three-way table is from
  ``Y_1`` and ``Y_2`` being conditionally independent given ``Y_3``.
* **Two-stage experiments.** :func:`sample_die_coins` rolls a die and tosses as many coins;
  :func:`nested_variance` estimates the two terms of the law of total variance from a nested
  simulation, correcting the between-groups term for the noise of the group means.
  :func:`sample_random_sum` and :func:`random_sum_moments` treat random sums
  ``S = X_1 + ... + X_N``.
* **Poisson thinning and the Poisson--Gamma mixture.** :func:`thinning_table` is the joint
  density of ``(X, Y)`` with ``X ~ P(lam)`` and ``Y | X = n ~ B(n, p)``, :func:`sample_thinning`
  simulates it. :func:`negbin_pmf` is the law ``BN(alpha, lam / (lam + 1))`` of a Poisson
  variable with a ``Gamma(alpha, lam)`` parameter, :func:`poisson_gamma_pmf_quad` computes the
  same law by integrating the mixture numerically, :func:`gamma_posterior` gives the law
  ``Gamma(alpha + k, lam + 1)`` of the parameter given ``Y = k``, and
  :func:`sample_poisson_gamma` simulates the pair. :func:`sample_gamma_conditional` simulates the
  pair of the second worked exercise, whose ``Y`` is not integrable. :func:`beta_binomial_pmf` and
  :func:`beta_posterior` do the same for a binomial variable with a Beta parameter.
* **The L2 projection.** :func:`indicator_features` builds the design matrix of the indicators
  of bins of ``Y``; :func:`l2_projection` is the least-squares projection of ``X`` on the span of
  given features (for indicator features it returns the bin averages: the conditional
  expectation given the sigma-algebra generated by the bins, under the empirical measure);
  :func:`bin_regression` computes the same bin averages without the design matrix;
  :func:`affine_predictor` is the best affine predictor. For the signal-plus-noise example
  ``Y = X + W`` with ``X ~ Exp(1)`` and ``W ~ N(0, sigma^2)``, :func:`signal_posterior_mean` is
  ``E[X | Y = y]`` in closed form and :func:`signal_mse` its mean squared error.
* **Binned conditional means.** :func:`binned_means` averages ``x`` over bins of ``y``, with
  standard errors, to look at ``E[X | Y]`` in a simulation.
"""
