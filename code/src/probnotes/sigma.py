"""Algebras and sigma-algebras on finite sets (Chapter 1).

On a finite set ``X`` every family of subsets is finite, so countable unions reduce to finite ones
and the sigma-algebra generated by a family can be computed exactly. Two independent methods are
provided:

* by **closure**: start from the family and ``X``, and add complements and pairwise unions until
  nothing new appears (:func:`closure_steps`, :func:`generate` with ``method="closure"``);
* by **atoms**: group the points of ``X`` by which sets of the family contain them; the groups are
  the atoms, and the generated sigma-algebra consists of all unions of atoms
  (:func:`atoms`, :func:`generate` with ``method="atoms"``).

Subsets are returned as ``frozenset``; a family is any iterable of iterables of points of ``X``.
The module also checks the axioms of an algebra, counts the sigma-algebras on an ``n``-point set
(Bell numbers), works with the finite unions of intervals ``[a, b)`` of Exercise 1 of the notes,
and traces the eight generating families of the Borel sets on a finite grid.
"""
from __future__ import annotations

from itertools import combinations
from typing import Iterable, Iterator, Sequence

import numpy as np

__all__ = [
    "membership_matrix", "atoms", "atoms_from_matrix", "unions_of", "generate", "closure_steps",
    "check_axioms", "is_algebra", "is_sigma_algebra", "bell", "set_partitions", "sigma_algebras",
    "count_sigma_algebras", "count_algebras_bruteforce", "interval_union", "interval_complement",
    "borel_generator_traces", "BOREL_FAMILIES",
]


# ---------------------------------------------------------------------------------------------
# families of subsets of a finite set
# ---------------------------------------------------------------------------------------------
def _points(X) -> list:
    pts = list(X)
    if len(set(pts)) != len(pts):
        raise ValueError("the points of X must be distinct")
    return pts


def _family(family, X) -> list[frozenset]:
    """The family as a list of frozensets, after checking that every set is a subset of X."""
    ground = set(X)
    fam = [frozenset(E) for E in family]
    for E in fam:
        if not E <= ground:
            raise ValueError(f"{set(E)} is not a subset of X")
    return fam


def membership_matrix(family, X) -> np.ndarray:
    """Boolean matrix ``M`` with ``M[j, k] = (X[k] in E_j)``: one row per set of the family."""
    pts = _points(X)
    fam = _family(family, pts)
    index = {x: k for k, x in enumerate(pts)}
    M = np.zeros((len(fam), len(pts)), dtype=bool)
    for j, E in enumerate(fam):
        M[j, [index[x] for x in E]] = True
    return M


def atoms_from_matrix(M: np.ndarray, X: Sequence | None = None) -> list[frozenset]:
    """Atoms of the sigma-algebra generated by the rows of a boolean matrix.

    Column ``k`` is the membership pattern of the point ``X[k]`` (``k`` itself if ``X`` is None).
    Two points lie in the same atom if and only if they have the same pattern. The atoms are
    returned in the order of their first point.
    """
    M = np.asarray(M, dtype=bool)
    n = M.shape[1]
    pts = list(range(n)) if X is None else _points(X)
    if len(pts) != n:
        raise ValueError("X must have one point per column of M")
    if n == 0:
        raise ValueError("X must be non-empty")
    if M.shape[0] == 0:                      # no sets: the trivial sigma-algebra {emptyset, X}
        return [frozenset(pts)]
    _, first, inverse = np.unique(M.T, axis=0, return_index=True, return_inverse=True)
    inverse = np.asarray(inverse).ravel()
    order = np.argsort(first)                # atom labels sorted by first point
    return [frozenset(pts[k] for k in np.flatnonzero(inverse == lab)) for lab in order]


def atoms(family, X) -> list[frozenset]:
    """Atoms of sigma(family) on the finite set X: the non-empty sets of the form
    ``F_1 & ... & F_m`` with each ``F_j`` either ``E_j`` or its complement."""
    pts = _points(X)
    return atoms_from_matrix(membership_matrix(family, pts), pts)


def unions_of(blocks: Iterable[frozenset]) -> set[frozenset]:
    """All unions of the given sets, including the empty union: 2**k sets for k disjoint blocks."""
    blocks = [frozenset(b) for b in blocks]
    out = {frozenset()}
    for b in blocks:
        out |= {s | b for s in out}
    return out


def _to_masks(family: list[frozenset], pts: list) -> np.ndarray:
    index = {x: k for k, x in enumerate(pts)}
    return np.array([sum(1 << index[x] for x in E) for E in family], dtype=np.int64)


def _from_mask(m: int, pts: list) -> frozenset:
    return frozenset(x for k, x in enumerate(pts) if (int(m) >> k) & 1)


def closure_steps(family, X) -> list[set[frozenset]]:
    """The families F_0, F_1, ... of the closure algorithm, until it stabilises.

    ``F_0`` is the family together with ``X``; ``F_{r+1}`` adds to ``F_r`` the complements of its
    sets and the unions of any two of its sets. The last family returned is sigma(family).
    Sets are handled as bit masks, so X may have up to 62 points (and the result 2**k sets).
    """
    pts = _points(X)
    if not pts:
        raise ValueError("X must be non-empty")
    if len(pts) > 62:
        raise ValueError("at most 62 points")
    full = (1 << len(pts)) - 1
    masks = np.unique(np.append(_to_masks(_family(family, pts), pts), full))
    steps = [masks]
    while True:
        new = np.unique(np.concatenate([masks, full ^ masks, np.bitwise_or.outer(masks, masks).ravel()]))
        if len(new) == len(masks):
            break
        masks = new
        steps.append(masks)
    return [{_from_mask(m, pts) for m in s} for s in steps]


def generate(family, X, method: str = "atoms") -> set[frozenset]:
    """The sigma-algebra generated by ``family`` on the finite set ``X``, as a set of frozensets."""
    if method == "atoms":
        return unions_of(atoms(family, X))
    if method == "closure":
        return closure_steps(family, X)[-1]
    raise ValueError("method must be 'atoms' or 'closure'")


# ---------------------------------------------------------------------------------------------
# axioms
# ---------------------------------------------------------------------------------------------
def check_axioms(F, X) -> dict:
    """Check the axioms of an algebra of subsets of X (the definition at the start of Chapter 1).

    Returns a dict with keys
    ``"nonempty"`` (bool), ``"contains_X"`` (bool),
    ``"complements"`` (``None`` if closed under complements, else a set whose complement is missing),
    ``"unions"`` (``None`` if closed under unions of two sets, else a pair whose union is missing).
    """
    pts = _points(X)
    fam = set(_family(F, pts))
    ground = frozenset(pts)
    index = {x: k for k, x in enumerate(pts)}
    ordered = sorted(fam, key=lambda S: (len(S), sorted(index[x] for x in S)))
    bad_c = next((A for A in ordered if ground - A not in fam), None)
    bad_u = None
    for A, B in combinations(ordered, 2):
        if A | B not in fam:
            bad_u = (A, B)
            break
    return {"nonempty": bool(fam), "contains_X": ground in fam, "complements": bad_c, "unions": bad_u}


def is_algebra(F, X) -> bool:
    """True if F is a non-empty family containing X, closed under complements and finite unions."""
    r = check_axioms(F, X)
    return r["nonempty"] and r["contains_X"] and r["complements"] is None and r["unions"] is None


def is_sigma_algebra(F, X) -> bool:
    """On a finite X a family of subsets is finite, so a countable union of its members is a union
    of finitely many of them: an algebra is automatically a sigma-algebra."""
    return is_algebra(F, X)


# ---------------------------------------------------------------------------------------------
# counting sigma-algebras on {1, ..., n}
# ---------------------------------------------------------------------------------------------
def bell(n: int) -> int:
    """The Bell number B_n, the number of partitions of an n-point set (B_0 = 1), via Bell's triangle."""
    if n < 0:
        raise ValueError("n must be >= 0")
    row = [1]
    for _ in range(n):
        new = [row[-1]]
        for v in row:
            new.append(new[-1] + v)
        row = new
    return row[0]


def set_partitions(X) -> Iterator[list[frozenset]]:
    """All partitions of the finite set X into non-empty blocks (X non-empty)."""
    pts = _points(X)
    if not pts:
        yield []
        return
    first, rest = pts[0], pts[1:]
    for p in set_partitions(rest):
        yield [frozenset([first])] + p                      # first point alone
        for j in range(len(p)):                             # or added to an existing block
            yield p[:j] + [p[j] | {first}] + p[j + 1:]


def sigma_algebras(X) -> Iterator[frozenset]:
    """All sigma-algebras on the finite set X, one for each partition of X into atoms."""
    for p in set_partitions(X):
        yield frozenset(unions_of(p))


def count_sigma_algebras(n: int) -> int:
    """Number of sigma-algebras on an n-point set: the Bell number B_n."""
    return bell(n)


def count_algebras_bruteforce(n: int) -> int:
    """Count, by checking all 2**(2**n) families of subsets of {0, ..., n-1}, those that are algebras
    (hence sigma-algebras). Vectorised over the families; feasible for n <= 4."""
    if not 0 <= n <= 4:
        raise ValueError("brute force only for 0 <= n <= 4")
    S = 1 << n                                      # number of subsets; subset s is a bit mask
    full = S - 1
    fams = np.arange(1 << S, dtype=np.int64)        # family f contains subset s iff bit s of f is 1
    F = ((fams[:, None] >> np.arange(S)) & 1).astype(bool)
    s = np.arange(S)
    ok = F[:, full].copy()                          # contains X (hence non-empty)
    ok &= np.all(~F | F[:, full ^ s], axis=1)       # complements
    U = s[:, None] | s[None, :]
    for a in range(S):                              # unions of two members, one row at a time
        ok &= np.all(~(F[:, [a]] & F) | F[:, U[a]], axis=1)
    return int(ok.sum())


# ---------------------------------------------------------------------------------------------
# Exercise 1 of the notes: finite unions of intervals [a, b) in [0, 1)
# ---------------------------------------------------------------------------------------------
def interval_union(*sets) -> list[tuple]:
    """Union of finite unions of half-open intervals, each given as a list of pairs (a, b) for [a, b).

    Returns the canonical form: disjoint, non-empty, sorted, and with touching intervals merged
    (``[a, b) | [b, c) = [a, c)``). Works with floats, ``fractions.Fraction`` or any ordered numbers.
    """
    ivs = sorted((a, b) for S in sets for (a, b) in S if a < b)
    out: list[list] = []
    for a, b in ivs:
        if out and a <= out[-1][1]:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    return [tuple(iv) for iv in out]


def interval_complement(A, lo=0, hi=1) -> list[tuple]:
    """Complement in [lo, hi) of a finite union of intervals [a, b) contained in [lo, hi):
    ``[lo, a_1) | [b_1, a_2) | ... | [b_n, hi)``, in canonical form."""
    pieces, left = [], lo
    for a, b in interval_union(A):
        if a < lo or b > hi:
            raise ValueError("intervals must lie in [lo, hi)")
        pieces.append((left, a))
        left = b
    pieces.append((left, hi))
    return interval_union(pieces)


# ---------------------------------------------------------------------------------------------
# the eight generating families of B(R), traced on a finite grid
# ---------------------------------------------------------------------------------------------
BOREL_FAMILIES = {
    1: "(a, b)", 2: "(a, b]", 3: "[a, b)", 4: "[a, b]",
    5: "(-inf, a)", 6: "(-inf, a]", 7: "(a, +inf)", 8: "[a, +inf)",
}


def borel_generator_traces(i: int, grid, endpoints) -> np.ndarray:
    """Traces on ``grid`` of the sets of the family E_i whose endpoints lie in ``endpoints``.

    E_1, ..., E_4 are the intervals (a,b), (a,b], [a,b), [a,b] with a < b; E_5, ..., E_8 are the
    half-lines (-inf,a), (-inf,a], (a,+inf), [a,+inf). Returns a boolean matrix with one row per set
    and one column per grid point (a membership matrix, to pass to :func:`atoms_from_matrix`).
    """
    g = np.asarray(grid, dtype=float)[None, :]
    e = np.unique(np.asarray(endpoints, dtype=float))
    if i in (1, 2, 3, 4):
        ia, ib = np.triu_indices(len(e), k=1)              # all pairs a < b
        a, b = e[ia][:, None], e[ib][:, None]
        left = (a < g) if i in (1, 2) else (a <= g)
        right = (g < b) if i in (1, 3) else (g <= b)
        return left & right
    a = e[:, None]
    return {5: g < a, 6: g <= a, 7: g > a, 8: g >= a}[i]
