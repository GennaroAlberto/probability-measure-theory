def sample_poisson_sum(n: int, lam: float, mu: float, seed=None):
    """``n`` draws of ``(X, Z) = (X, X + Y)``, ``X ~ P(lam)``, ``Y ~ P(mu)`` independent."""
    rng = np.random.default_rng(seed)
    x = rng.poisson(lam, n)
    return x, x + rng.poisson(mu, n)


def sample_exponential_sum(n: int, lam: float = 1.0, seed=None):
    """``n`` draws of ``(X, Z) = (X, X + Y)``, ``X, Y ~ Exp(lam)`` independent."""
    rng = np.random.default_rng(seed)
    x = rng.exponential(1 / lam, n)
    return x, x + rng.exponential(1 / lam, n)


# pairs (X, Y) of independent variables and h with E[X | X + Y] = h(X + Y)
SUM_PAIRS = {
    "exponential": ("X, Y ~ Exp(1)", lambda z: z / 2),
    "uniform": ("X, Y ~ U(0, 1)", lambda z: z / 2),
    "normal": ("X, Y ~ N(0, 1)", lambda z: z / 2),
    "gamma": ("X ~ Gamma(2, 1), Y ~ Exp(1)", lambda z: 2 * z / 3),
}


def sample_sum(kind: str, n: int, seed=None):
    """``n`` draws of ``(X, Z) = (X, X + Y)`` for one of the pairs of :data:`SUM_PAIRS`.

    For the three i.i.d. pairs ``E[X | Z] = Z / 2`` by symmetry; for ``X ~ Gamma(2, 1)`` and
    ``Y ~ Exp(1)``, ``E[X | Z] = 2 Z / 3`` (``X / Z`` is ``Beta(2, 1)`` and independent of ``Z``).
    """
    rng = np.random.default_rng(seed)
    if kind == "exponential":
        x, y = rng.exponential(1.0, n), rng.exponential(1.0, n)
    elif kind == "uniform":
        x, y = rng.random(n), rng.random(n)
    elif kind == "normal":
        x, y = rng.standard_normal(n), rng.standard_normal(n)
    elif kind == "gamma":
        x, y = rng.gamma(2.0, 1.0, n), rng.exponential(1.0, n)
    else:
        raise ValueError(f"unknown pair {kind!r}; choose from {sorted(SUM_PAIRS)}")
    return x, x + y


@dataclass
class BinnedMean:
    """Averages of ``x`` over the bins ``[edges[k], edges[k+1])`` of ``z``."""
    edges: np.ndarray
    count: np.ndarray       # samples in each bin
    mean_z: np.ndarray      # average of z in each bin
    mean_x: np.ndarray      # average of x in each bin: the cell average
    se_x: np.ndarray        # standard error of mean_x

    @property
    def centres(self) -> np.ndarray:
        return (self.edges[:-1] + self.edges[1:]) / 2


def binned_conditional_mean(z, x, edges) -> BinnedMean:
    """Cell averages of ``x`` over bins of ``z``: an estimate of ``E[X | Z in bin]``.

    Under the empirical measure of the sample, ``mean_x`` is exactly ``E[X | G]`` on each bin, for
    ``G`` generated by the partition ``{Z in bin_k}``. Bins without samples give ``nan``; bins
    with a single sample have ``se_x = nan``.
    """
    z, x = np.asarray(z, dtype=float), np.asarray(x, dtype=float)
    edges = np.asarray(edges, dtype=float)
    k = np.searchsorted(edges, z, side="right") - 1
    ok = (k >= 0) & (k < len(edges) - 1)
    k, zz, xx = k[ok], z[ok], x[ok]
    nb = len(edges) - 1
    cnt = np.bincount(k, minlength=nb).astype(float)
    with np.errstate(invalid="ignore", divide="ignore"):
        mz = np.bincount(k, weights=zz, minlength=nb) / cnt
        mx = np.bincount(k, weights=xx, minlength=nb) / cnt
        ss = np.bincount(k, weights=(xx - mx[k]) ** 2, minlength=nb)
        se = np.sqrt(ss / (cnt - 1) / cnt)
    se = np.where(cnt > 1, se, np.nan)
    return BinnedMean(edges, cnt.astype(int), mz, mx, se)


def cell_average(z, x, edges) -> np.ndarray:
    """The random variable ``omega -> average of x over the bin of z(omega)``, sample by sample
    (``nan`` outside the bins): the empirical ``E[X | sigma(bins of Z)]``."""
    b = binned_conditional_mean(z, x, edges)
    z = np.asarray(z, dtype=float)
    k = np.searchsorted(b.edges, z, side="right") - 1
    ok = (k >= 0) & (k < len(b.edges) - 1)
    out = np.full(z.shape, np.nan)
    out[ok] = b.mean_x[k[ok]]
    return out


@dataclass
class MCEstimate:
    """Monte Carlo estimates with standard errors."""
    mean: np.ndarray
    se: np.ndarray


def defining_property_mc(x, hz, z, intervals) -> MCEstimate:
    """Estimate ``E[(X - h(Z)) 1{a < Z <= b}]`` for each interval ``(a, b]``.

    ``hz`` is the array ``h(Z)`` of a candidate for ``E[X | Z]``. For the true conditional
    expectation every value is ``0`` (property 2 of the definition, with ``A = {Z in (a, b]}``), so
    the estimates should be within a few standard errors of ``0``.
    """
    x, hz, z = (np.asarray(a, dtype=float) for a in (x, hz, z))
    n = len(x)
    means, ses = [], []
    for a, b in intervals:
        d = (x - hz) * ((z > a) & (z <= b))
        means.append(d.mean())
        ses.append(d.std(ddof=1) / np.sqrt(n))
    return MCEstimate(np.array(means), np.array(ses))


def uniform_renewal_count(n: int, x: float = 1.0, seed=None) -> np.ndarray:
    """``n`` independent draws of ``N(x) = min{k >= 1 : U_1 + ... + U_k > x}``, ``U_i ~ U(0, 1)``
    i.i.d.; for ``0 < x <= 1``, ``E[N(x)] = e^x``."""
    rng = np.random.default_rng(seed)
    s = np.zeros(n)
    count = np.zeros(n, dtype=int)
    active = np.ones(n, dtype=bool)
    while active.any():
        idx = np.flatnonzero(active)
        s[idx] += rng.random(idx.size)
        count[idx] += 1
        active[idx] = s[idx] <= x
    return count
