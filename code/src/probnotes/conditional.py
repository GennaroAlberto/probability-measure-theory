def midpoints(a: float, b: float, n: int) -> np.ndarray:
    """The ``n`` midpoints of the uniform partition of ``[a, b]``."""
    return a + (b - a) * (np.arange(n) + 0.5) / n


def conditional_density(f: Callable, y, x_lo: float, x_hi: float, n: int = 4000):
    """``f_{X|Y=y}`` on the midpoint grid of ``[x_lo, x_hi]``, from a joint density ``f(x, y)``.

    Returns ``(x, c)`` with ``c[:, k] = f(x, y_k) / int f(u, y_k) du`` (midpoint rule); columns with
    ``int f(u, y_k) du = 0`` (that is, ``f_Y(y_k) = 0``) are ``nan``. ``f`` must accept arrays.
    """
    x = midpoints(x_lo, x_hi, n)
    y = np.atleast_1d(np.asarray(y, dtype=float))
    vals = np.asarray(f(x[:, None], y[None, :]), dtype=float)
    norm = vals.sum(axis=0) * (x_hi - x_lo) / n
    with np.errstate(invalid="ignore", divide="ignore"):
        c = np.where(norm > 0, vals / np.where(norm > 0, norm, 1.0), np.nan)
    return x, c


def conditional_mean_from_density(f: Callable, y, x_lo: float, x_hi: float, n: int = 4000) -> np.ndarray:
    """``h(y) = int x f(x, y) dx / int f(x, y) dx`` by the midpoint rule on ``[x_lo, x_hi]``
    (``nan`` where ``f_Y(y) = 0``); this is ``E[X | Y = y]`` of the notes."""
    x, c = conditional_density(f, y, x_lo, x_hi, n)
    return (x[:, None] * c).sum(axis=0) * (x_hi - x_lo) / n


