def _exact(*arrays) -> bool:
    return any(isinstance(v, Fraction) for a in arrays for v in np.asarray(a, dtype=object).ravel())


def _arr(a, exact: bool) -> np.ndarray:
    return np.asarray(a, dtype=object) if exact else np.asarray(a, dtype=float)


def _labels(y) -> list[Hashable]:
    """Values of a random variable on a finite space, as hashable labels (rows become tuples)."""
    y = np.asarray(y, dtype=object)
    if y.ndim == 1:
        return [v.item() if hasattr(v, "item") else v for v in y]
    return [tuple(row) for row in y.reshape(len(y), -1)]


def two_dice(exact: bool = True):
    """The 36 equally likely outcomes of two fair dice: ``(p, d1, d2)``, arrays over ``omega``."""
    d1, d2 = np.divmod(np.arange(36), 6)
    p = np.full(36, Fraction(1, 36), dtype=object) if exact else np.full(36, 1 / 36)
    return p, d1 + 1, d2 + 1


def conditional_expectation_given(x, y, p):
    """``E[X | Y]`` on a finite space, for ``X`` and ``Y`` given as arrays over ``omega``.

    Returns ``(h, xhat)``: ``h`` is a dict ``{y: E[X | Y = y]}`` over the values of ``Y`` with
    positive probability, and ``xhat[omega] = h(Y(omega))`` (``nan`` where ``P(Y = y) = 0``). ``Y``
    may be vector-valued (a 2-d array, one row per ``omega``). Exact if ``x`` or ``p`` holds
    :class:`~fractions.Fraction` values.
    """
    exact = _exact(x, p)
    x, p = _arr(x, exact), _arr(p, exact)
    lab = _labels(y)
    if not (len(x) == len(p) == len(lab)):
        raise ValueError("x, y and p must have one entry per point of Omega")
    num: dict = {}
    den: dict = {}
    zero = Fraction(0) if exact else 0.0
    for xi, pi, li in zip(x, p, lab):
        num[li] = num.get(li, zero) + xi * pi
        den[li] = den.get(li, zero) + pi
    h = {v: num[v] / den[v] for v in den if den[v] > 0}
    xhat = np.array([h.get(v, np.nan) for v in lab], dtype=object if exact else float)
    return h, xhat


def partition_expectation(x, p, labels) -> np.ndarray:
    """``E[X | G]`` where ``G`` is generated by the partition ``{labels == c}`` of a finite space.

    On each cell of positive probability the value is the cell average
    ``E[X 1_cell] / P(cell)``; on cells of probability ``0`` it is ``nan``. For float input the
    computation is vectorised, so ``Omega`` can be a fine grid or a large sample.
    """
    if _exact(x, p):
        return conditional_expectation_given(x, labels, p)[1]
    x, p = np.asarray(x, dtype=float), np.asarray(p, dtype=float)
    _, inv = np.unique(np.asarray(labels), return_inverse=True, axis=None)
    inv = inv.ravel()
    mass = np.bincount(inv, weights=p)
    tot = np.bincount(inv, weights=x * p)
    with np.errstate(invalid="ignore", divide="ignore"):
        avg = np.where(mass > 0, tot / np.where(mass > 0, mass, 1.0), np.nan)
    return avg[inv]


def sigma_from_partition(labels) -> set[frozenset]:
    """All events of the sigma-algebra generated by the partition ``{labels == c}`` of
    ``{0, ..., N-1}``: the ``2^k`` unions of the ``k`` cells (via :func:`probnotes.sigma.unions_of`).
    """
    lab = _labels(labels)
    cells: dict = {}
    for i, v in enumerate(lab):
        cells.setdefault(v, set()).add(i)
    if len(cells) > 20:
        raise ValueError("too many cells to list every event")
    return unions_of(frozenset(c) for c in cells.values())


def check_conditional_expectation(x, xhat, p, labels) -> dict:
    """Check properties 1) and 2) of Kolmogorov's definition for ``G = sigma(partition)``.

    1) ``xhat`` is ``G``-measurable, that is, constant on every cell;
    2) ``sum_{omega in A} xhat p = sum_{omega in A} x p`` for **every** event ``A`` of ``G``.

    Returns ``{"measurable": bool, "max_gap": ..., "n_events": ...}``, where ``max_gap`` is the
    largest ``|E[(X - xhat) 1_A]|`` over the events; it is exactly ``0`` with fractions.
    """
    exact = _exact(x, xhat, p)
    x, xhat, p = _arr(x, exact), _arr(xhat, exact), _arr(p, exact)
    lab = _labels(labels)
    first: dict = {}
    measurable = True
    for v, xh in zip(lab, xhat):
        if v in first and not (first[v] == xh or (not exact and abs(first[v] - xh) <= 1e-12 * (1 + abs(xh)))):
            measurable = False
        first.setdefault(v, xh)
    d = (x - xhat) * p
    events = sigma_from_partition(lab)
    gaps = [abs(sum((d[i] for i in A), Fraction(0) if exact else 0.0)) for A in events]
    return {"measurable": measurable, "max_gap": max(gaps), "n_events": len(events)}


def factor_through(z, y) -> dict:
    """Doob--Dynkin on a finite space: find ``h`` with ``Z = h(Y)``.

    ``Z`` is ``sigma(Y)``-measurable exactly when it is constant on every level set ``{Y = v}``;
    then ``h = {v: value of Z on {Y = v}}`` (on ``Y(Omega)``; any value elsewhere). Otherwise a
    :class:`ValueError` names a level set on which ``Z`` takes two values. ``Y`` may be
    vector-valued (a 2-d array, one row per ``omega``).
    """
    zl, yl = _labels(z), _labels(y)
    if len(zl) != len(yl):
        raise ValueError("z and y must have one entry per point of Omega")
    h: dict = {}
    for zi, yi in zip(zl, yl):
        if yi in h and h[yi] != zi:
            raise ValueError(f"not sigma(Y)-measurable: on {{Y = {yi}}} Z takes the values {h[yi]} and {zi}")
        h.setdefault(yi, zi)
    return h


