"""Conditioning and conditional expectation (Chapter 11).

Four groups of tools, in the order of the chapter:

* **Discrete tables.** A joint discrete density with finitely many values is a table
  ``f[i, j] = P(X = x_i, Y = y_j)``. :func:`conditional_pmf` normalises its columns (or rows),
  giving ``f_{X|Y=y_j}``, and :func:`conditional_mean` gives ``h(y_j) = E[X | Y = y_j]``; the
  columns with ``f_Y(y_j) = 0`` are left undefined, as the notes allow. For independent Poisson
  variables, :func:`poisson_sum_table` is the joint density of ``(X, X + Y)`` and
  :func:`poisson_sum_conditional` the law of ``X`` given ``X + Y = m``, computed from the joint
  density exactly as in the worked exercise of the notes.
* **Finite probability spaces.** ``Omega = {0, ..., N-1}`` with a vector of masses ``p``; a random
  variable is an array indexed by ``omega``. :func:`conditional_expectation_given` returns
  ``E[X | Y]`` as ``h`` and ``h(Y)``, :func:`partition_expectation` returns ``E[X | G]`` for ``G``
  generated by a partition (cell averages), :func:`sigma_from_partition` lists the events of
  ``G``, and :func:`check_conditional_expectation` verifies the two properties of Kolmogorov's
  definition on every event of ``G``. :func:`factor_through` is the Doob--Dynkin theorem on a
  finite space: it returns ``h`` with ``Z = h(Y)``, or reports a level set of ``Y`` on which ``Z``
  is not constant. With masses given as :class:`fractions.Fraction` everything is exact.
* **Densities on a grid.** :func:`conditional_density` and :func:`conditional_mean_from_density`
  compute ``f_{X|Y=y}`` and ``h(y)`` from a joint density by the midpoint rule.
* **Monte Carlo.** :func:`sample_poisson_sum`, :func:`sample_exponential_sum` and
  :func:`sample_sum` draw the pairs ``(X, X + Y)`` used in the chapter;
  :func:`binned_conditional_mean` computes the averages of ``X`` over bins of ``Z``, which are
  ``E[X | G]`` for the sigma-algebra ``G`` generated by the bins under the empirical measure, and
  :func:`defining_property_mc` estimates ``E[(X - h(Z)) 1{Z in B}]`` with standard errors.
  :func:`uniform_renewal_count` draws ``N(x) = min{n : U_1 + ... + U_n > x}``.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from typing import Callable, Hashable, Sequence

import numpy as np
from scipy import stats

from probnotes.sigma import unions_of

